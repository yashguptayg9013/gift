/**
 * Generates the endpoint reference (method, path, required permissions) from the
 * live route metadata so API_DOCUMENTATION.md never drifts from the code.
 * Usage: pnpm --filter @puja/api docs:api > ../../docs/API_ENDPOINTS.md
 */
import 'reflect-metadata';
import { RequestMethod } from '@nestjs/common';
import { METHOD_METADATA, PATH_METADATA } from '@nestjs/common/constants';
import { DiscoveryModule, DiscoveryService, NestFactory } from '@nestjs/core';
import { Module } from '@nestjs/common';
import { IS_PUBLIC_KEY, PERMISSIONS_KEY, PERMISSIONS_MODE_KEY } from '../common/decorators';
import { loadEnv } from '../config/env';

async function main() {
  process.env.JOBS_ENABLED = 'false';
  loadEnv();
  const { AppModule } = await import('../app.module');
  @Module({ imports: [AppModule, DiscoveryModule] })
  class DocsModule {}
  const app = await NestFactory.createApplicationContext(DocsModule, { logger: false });
  const discovery = app.get(DiscoveryService);
  const rows: { tag: string; method: string; path: string; access: string }[] = [];
  for (const wrapper of discovery.getControllers()) {
    const ctrl = wrapper.metatype as (new (...a: unknown[]) => unknown) | undefined;
    if (!ctrl) continue;
    const base = (Reflect.getMetadata(PATH_METADATA, ctrl) as string) ?? '';
    const tags = (Reflect.getMetadata('swagger/apiUseTags', ctrl) as string[] | undefined) ?? [base || 'root'];
    const proto = ctrl.prototype as Record<string, unknown>;
    for (const name of Object.getOwnPropertyNames(proto)) {
      const fn = proto[name];
      if (name === 'constructor' || typeof fn !== 'function') continue;
      const method = Reflect.getMetadata(METHOD_METADATA, fn) as RequestMethod | undefined;
      if (method === undefined) continue;
      const sub = (Reflect.getMetadata(PATH_METADATA, fn) as string) ?? '';
      const isPublic = Reflect.getMetadata(IS_PUBLIC_KEY, fn) ?? Reflect.getMetadata(IS_PUBLIC_KEY, ctrl);
      const perms = (Reflect.getMetadata(PERMISSIONS_KEY, fn) ?? Reflect.getMetadata(PERMISSIONS_KEY, ctrl)) as string[] | undefined;
      const mode = Reflect.getMetadata(PERMISSIONS_MODE_KEY, fn) === 'any' ? ' (any)' : '';
      const path = `/api/v1/${[base, sub].filter((p) => p && p !== '/').join('/')}`.replace(/\/+/g, '/').replace(/\/$/, '');
      rows.push({ tag: tags[0], method: RequestMethod[method], path, access: isPublic ? 'public' : perms?.length ? perms.map((p) => `\`${p}\``).join(mode ? ' or ' : ', ') + mode : 'authenticated' });
    }
  }
  await app.close();
  rows.sort((a, b) => a.tag.localeCompare(b.tag) || a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
  const out: string[] = ['# API endpoint reference', '', '> Generated by `pnpm --filter @puja/api docs:api` from route metadata. Do not edit by hand.', '', `${rows.length} endpoints. Interactive OpenAPI docs: \`/api/docs\` (non-production) and \`/api/docs/openapi.json\`.`, ''];
  for (const tag of [...new Set(rows.map((r) => r.tag))]) {
    out.push(`## ${tag}`, '', '| Method | Path | Access |', '|---|---|---|');
    for (const r of rows.filter((x) => x.tag === tag)) out.push(`| ${r.method} | \`${r.path}\` | ${r.access} |`);
    out.push('');
  }
  console.log(out.join('\n'));
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
