import { Injectable } from '@nestjs/common';
import { D, m2, ZERO } from '../../common/decimal';
import { dt, inr, num, PdfService } from '../../infra/pdf/pdf.service';
import { SettingsService } from '../settings/settings.service';
import { lineAmounts, SalesService } from './sales.service';

/** Two-digit GST state code from a GSTIN, if valid. */
const gstState = (gstin?: string | null) => (gstin && /^\d{2}/.test(gstin) ? gstin.slice(0, 2) : null);

@Injectable()
export class SalesDocumentsService {
  constructor(
    private readonly sales: SalesService,
    private readonly settings: SettingsService,
    private readonly pdf: PdfService,
  ) {}

  private async company() {
    const c = await this.settings.get('company');
    return {
      raw: c,
      header: {
        name: c.tradeName || c.legalName,
        lines: [c.tradeName && c.legalName && c.tradeName !== c.legalName ? c.legalName : '', c.address, [c.city, c.state, c.pincode].filter(Boolean).join(', '), c.gstin ? `GSTIN: ${c.gstin}` : '', [c.phone, c.email].filter(Boolean).join(' · ')],
      },
    };
  }

  /**
   * Intra-state supply → CGST + SGST (half each); inter-state → IGST.
   * Determined from GSTIN state codes, falling back to state names. If unknown, tax is shown as GST.
   */
  private taxSplit(company: { gstin: string; stateCode: string; state: string }, customer: { gstin: string | null; state: string | null }) {
    const ours = gstState(company.gstin) ?? (company.stateCode || null);
    const theirs = gstState(customer.gstin);
    if (ours && theirs) return ours === theirs ? 'INTRA' : 'INTER';
    if (company.state && customer.state) return company.state.trim().toLowerCase() === customer.state.trim().toLowerCase() ? 'INTRA' : 'INTER';
    return 'UNKNOWN';
  }

  async quotationPdf(id: string) {
    const q = (await this.sales.quotation(id)) as unknown as QuoteLike;
    const { raw, header } = await this.company();
    const split = this.taxSplit(raw, q.customer);
    let taxTotal = ZERO;
    const rows = q.lines.map((l, i) => {
      const a = lineAmounts(l);
      taxTotal = taxTotal.plus(a.tax);
      return {
        n: String(i + 1),
        item: `${l.item.name}\n${l.item.code}${l.description && l.description !== l.item.name ? ` · ${l.description}` : ''}`,
        hsn: l.item.hsnCode ?? '',
        qty: `${num(l.quantity)} ${l.item.uom.code}`,
        rate: num(l.unitPrice),
        disc: Number(l.discountPct) ? `${num(l.discountPct)}%` : '',
        tax: `${num(l.taxRate)}%`,
        amount: num(a.net.plus(a.tax).toString()),
      };
    });
    const pdf = await this.pdf.render({
      title: 'Quotation',
      company: header,
      meta: [
        ['Quotation no.', q.number],
        ['Date', dt(q.quoteDate)],
        ['Valid until', dt(q.validUntil)],
      ],
      party: { heading: 'Quotation for', lines: customerLines(q.customer) },
      columns: [
        { key: 'n', label: '#', width: 3 },
        { key: 'item', label: 'Product', width: 26 },
        { key: 'hsn', label: 'HSN', width: 8 },
        { key: 'qty', label: 'Qty', width: 10, align: 'right' },
        { key: 'rate', label: 'Rate', width: 10, align: 'right' },
        { key: 'disc', label: 'Disc.', width: 7, align: 'right' },
        { key: 'tax', label: 'GST', width: 7, align: 'right' },
        { key: 'amount', label: 'Amount', width: 12, align: 'right' },
      ],
      rows,
      totals: this.totals(q.subtotal, q.discountTotal, taxTotal, q.total, split),
      notes: [
        { heading: 'Terms', text: q.terms || raw.quotationTerms },
        { heading: 'Notes', text: q.notes ?? '' },
      ],
      signatureLabel: 'Authorised signatory',
      footer: `Generated by PUJA OS · ${q.number}`,
    });
    return { filename: `${q.number.replace(/\//g, '-')}.pdf`, pdf };
  }

  async challanPdf(id: string) {
    const c = (await this.sales.challan(id)) as unknown as ChallanLike;
    const { raw, header } = await this.company();
    const split = this.taxSplit(raw, c.customer);
    let subtotal = ZERO;
    let tax = ZERO;
    const rows = c.lines.map((l, i) => {
      const a = lineAmounts({ quantity: l.quantity, unitPrice: l.salesOrderLine.unitPrice, discountPct: l.salesOrderLine.discountPct, taxRate: l.salesOrderLine.taxRate });
      subtotal = subtotal.plus(a.net);
      tax = tax.plus(a.tax);
      return { n: String(i + 1), item: `${l.item.name}\n${l.item.code}`, hsn: l.item.hsnCode ?? '', qty: `${num(l.quantity)} ${l.item.uom.code}`, value: num(a.net.toString()) };
    });
    const pdf = await this.pdf.render({
      title: 'Delivery Challan',
      company: header,
      meta: [
        ['Challan no.', c.number],
        ['Date', dt(c.challanDate)],
        ['Sales order', c.salesOrder.number],
        ['Customer PO', c.salesOrder.customerPoNumber ?? '—'],
        ['Vehicle no.', c.vehicleNo ?? '—'],
      ],
      party: { heading: 'Consignee', lines: customerLines(c.customer, true) },
      secondParty: c.transporter ? { heading: 'Transporter', lines: [c.transporter] } : undefined,
      columns: [
        { key: 'n', label: '#', width: 3 },
        { key: 'item', label: 'Description of goods', width: 40 },
        { key: 'hsn', label: 'HSN', width: 10 },
        { key: 'qty', label: 'Quantity', width: 14, align: 'right' },
        { key: 'value', label: 'Value (excl. tax)', width: 16, align: 'right' },
      ],
      rows,
      totals: [
        ['Taxable value', inr(m2(subtotal).toString())],
        ...(split === 'INTRA'
          ? ([
              ['CGST', inr(m2(tax.div(2)).toString())],
              ['SGST', inr(m2(tax.minus(m2(tax.div(2)))).toString())],
            ] as [string, string][])
          : ([[split === 'INTER' ? 'IGST' : 'GST', inr(m2(tax).toString())]] as [string, string][])),
        ['Total value', inr(m2(subtotal.plus(tax)).toString())],
      ],
      notes: [
        { heading: 'Remarks', text: c.remarks ?? '' },
        { heading: 'Declaration', text: 'Goods dispatched as per the sales order referenced above. Not a tax invoice.' },
      ],
      signatureLabel: 'Authorised signatory',
      footer: `Generated by PUJA OS · ${c.number}${c.status !== 'POSTED' ? ` · ${c.status}` : ''}`,
    });
    return { filename: `${c.number.replace(/\//g, '-')}.pdf`, pdf };
  }

  private totals(subtotal: number, discount: number, tax: ReturnType<typeof D>, total: number, split: string): [string, string][] {
    const out: [string, string][] = [['Subtotal', inr(subtotal)]];
    if (Number(discount)) out.push(['Discount', `- ${inr(discount)}`]);
    if (split === 'INTRA') {
      out.push(['CGST', inr(m2(tax.div(2)).toString())], ['SGST', inr(m2(tax.minus(m2(tax.div(2)))).toString())]);
    } else out.push([split === 'INTER' ? 'IGST' : 'GST', inr(m2(tax).toString())]);
    out.push(['Total', inr(total)]);
    return out;
  }
}

function customerLines(c: CustomerLike, shipping = false) {
  return [c.companyName, c.contactPerson ? `Attn: ${c.contactPerson}` : '', (shipping && c.shippingAddress) || c.billingAddress || '', [c.city, c.state, c.pincode].filter(Boolean).join(', '), c.gstin ? `GSTIN: ${c.gstin}` : '', c.phone ?? ''];
}

interface CustomerLike {
  companyName: string;
  contactPerson: string | null;
  billingAddress: string | null;
  shippingAddress: string | null;
  city: string | null;
  state: string | null;
  pincode: string | null;
  gstin: string | null;
  phone: string | null;
}
interface ItemLike {
  code: string;
  name: string;
  hsnCode: string | null;
  uom: { code: string };
}
interface QuoteLike {
  number: string;
  quoteDate: string;
  validUntil: string | null;
  subtotal: number;
  discountTotal: number;
  total: number;
  terms: string | null;
  notes: string | null;
  customer: CustomerLike;
  lines: { quantity: number; unitPrice: number; discountPct: number; taxRate: number; description: string | null; item: ItemLike }[];
}
interface ChallanLike {
  number: string;
  status: string;
  challanDate: string;
  vehicleNo: string | null;
  transporter: string | null;
  remarks: string | null;
  customer: CustomerLike;
  salesOrder: { number: string; customerPoNumber: string | null };
  lines: { quantity: number; item: ItemLike; salesOrderLine: { unitPrice: number; discountPct: number; taxRate: number } }[];
}
