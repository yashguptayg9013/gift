export function blankDecision(id: string, now = new Date()): Decision {
  const iso = now.toISOString();
  return {
    id,
    title: "",
    category: "purchase",
    context: "",
    createdAt: iso,
    updatedAt: iso,
    upfrontCost: 0,
    monthlyCost: 0,
    horizonYears: 3,
    longTermValue: 5,
    reversibility: 3,
    timeCostHours: 0,
    alternatives: [],
    priorityImpacts: {},
    pros: [],
    cons: [],
    gutFeeling: 50,
    status: "open",
  };
}

function daysAgo(n: number) {
  return new Date(Date.now() - n * 864e5).toISOString();
}

function daysAhead(n: number) {
  return new Date(Date.now() + n * 864e5).toISOString().slice(0, 10);
}

